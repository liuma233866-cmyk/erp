CREATE TABLE IF NOT EXISTS central_products (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  public_id VARCHAR(40) NOT NULL,
  company_id BIGINT UNSIGNED NOT NULL,
  canonical_sku VARCHAR(128) NULL,
  title VARCHAR(500) NOT NULL,
  description TEXT NULL,
  brand VARCHAR(256) NULL,
  category_id VARCHAR(128) NULL,
  purchase_price DECIMAL(12,2) NULL,
  currency CHAR(3) NOT NULL DEFAULT 'CNY',
  package_length_cm DECIMAL(10,2) NULL,
  package_width_cm DECIMAL(10,2) NULL,
  package_height_cm DECIMAL(10,2) NULL,
  weight_kg DECIMAL(10,3) NULL,
  stock_count INT NOT NULL DEFAULT 0,
  status VARCHAR(32) NOT NULL DEFAULT 'collected',
  current_version INT UNSIGNED NOT NULL DEFAULT 1,
  created_by BIGINT UNSIGNED NULL,
  updated_by BIGINT UNSIGNED NULL,
  created_at DATETIME(3) NOT NULL,
  updated_at DATETIME(3) NOT NULL,
  row_version BIGINT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (id),
  UNIQUE KEY uq_central_products_public_id (public_id),
  KEY ix_central_products_company_status (company_id, status, updated_at),
  KEY ix_central_products_company_sku (company_id, canonical_sku),
  UNIQUE KEY uq_central_products_company_sku (company_id, canonical_sku)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
